/**
 * Career catalog — every `CareerId` in docs/IDS.md with 4–6 levels each.
 *
 * Pay is 2026 US figures at cost-of-living 1.0; the career system scales by region.
 * `hourly` levels are paid per hour worked; salaried levels have no `hourly`.
 * `shift.days` is the pool of days the employer schedules from; the career system picks
 * `round(hoursPerWeek / shiftLength)` of them at hire (so a 36h nurse works 3×12h).
 */
import type { SkillId, Weekday } from '../core/types';
import type { CareerDef, CareerLevel } from './types';

type Shift = CareerLevel['shift'];
const WEEKDAYS: Weekday[] = [1, 2, 3, 4, 5];
const ALL: Weekday[] = [0, 1, 2, 3, 4, 5, 6];
const WEEKEND_HEAVY: Weekday[] = [0, 3, 4, 5, 6];
const sh = (startH: number, endH: number, days: Weekday[]): Shift => ({ start: Math.round(startH * 60), end: Math.round(endH * 60), days });

const OFFICE = sh(9, 17, WEEKDAYS);
const OFFICE_LONG = sh(8.5, 18, WEEKDAYS);
const RETAIL_DAY = sh(10, 18, ALL);
const RETAIL_EVE = sh(14, 22, ALL);
const CAFE_OPEN = sh(6, 14, ALL);
const LUNCH_DINNER = sh(11, 19, ALL);
const DINNER = sh(16, 24, WEEKEND_HEAVY);
const BAR = sh(17, 24, WEEKEND_HEAVY);
const HOSP12 = sh(7, 19, ALL);
const HOSP_NIGHT = sh(19, 24, ALL);
const CLINIC = sh(8, 17, WEEKDAYS);
const SCHOOL = sh(7.5, 15.5, WEEKDAYS);
const EARLY = sh(5, 13, ALL);
const WAREHOUSE = sh(6, 14.5, ALL);
const TRADES = sh(7, 15.5, WEEKDAYS);
const EVENING_GUARD = sh(16, 24, ALL);
const JANITOR = sh(17, 23, ALL);
const GYM = sh(6, 12, ALL);
const GYM_EVE = sh(15, 21, ALL);
const AFTERNOON = sh(14, 20, ALL);
const CREATIVE = sh(10, 18, WEEKDAYS);
const FLEX = sh(10, 16, ALL);

interface LevelOpts {
  /** annual salary if >= 300, else hourly rate */
  pay: number;
  hours: number;
  shift: Shift;
  req?: Partial<Record<SkillId, number>>;
  tasks: string[];
  gain?: number;
  remote?: boolean;
}

function lv(title: string, o: LevelOpts): CareerLevel {
  const hourly = o.pay < 300 ? o.pay : undefined;
  const salary = hourly ? Math.round(hourly * o.hours * 52) : o.pay;
  return {
    title,
    salary,
    hourly,
    hoursPerWeek: o.hours,
    shift: o.shift,
    requiredSkills: o.req ?? {},
    tasks: o.tasks,
    dailyPerformanceGain: o.gain ?? 6,
    remoteEligible: o.remote ?? false,
  };
}

interface CareerOpts {
  name: string;
  description: string;
  icon: string;
  sector: CareerDef['sector'];
  venues: CareerDef['venues'];
  education: CareerDef['educationRequired'];
  skills: SkillId[];
  bg?: boolean;
  drug?: boolean;
  stress: number;
  physical: number;
  uniform?: string;
  tags?: string[];
  levels: CareerLevel[];
}

function career(id: string, o: CareerOpts): CareerDef {
  return {
    id,
    name: o.name,
    description: o.description,
    icon: o.icon,
    sector: o.sector,
    venues: o.venues,
    levels: o.levels,
    educationRequired: o.education,
    skills: o.skills,
    backgroundCheck: o.bg ?? false,
    drugTest: o.drug ?? false,
    stress: o.stress,
    physical: o.physical,
    uniform: o.uniform,
    tags: o.tags ?? [],
  };
}

